const fs = require("node:fs");
const path = require("node:path");

function main() {
  const domains = fs.readFileSync(path.join(__dirname, "../configs/doubao-domains.txt"), "utf8")
    .split(/\r?\n/).map(line => line.trim()).filter(line => line && !line.startsWith("#"));
  const rules = domains.map(domain =>
    `AND,((SRC-IP-CIDR,192.168.1.245/32),(DOMAIN-SUFFIX,${domain})),DIRECT`);
  rules.push("AND,((SRC-IP-CIDR,192.168.1.245/32),(DOMAIN,www.cloudflare.com)),DIRECT");
  const filters = [...domains, "www.cloudflare.com"].map(domain => `+.${domain}`);

  // OpenClash records these helper calls and applies them to its generated config.
  // https://github.com/vernesong/OpenClash/blob/master/luci-app-openclash/root/etc/openclash/custom/openclash_custom_overwrite.sh
  process.stdout.write([
    "# Generated by scripts/generate_openclash_override.js; do not edit.",
    `ruby_arr_insert_arr "$CONFIG_FILE" "['rules']" "0" '${JSON.stringify(rules)}'`,
    `ruby_uniq "$CONFIG_FILE" "['rules']"`,
    `ruby_arr_insert_arr "$CONFIG_FILE" "['dns']['fake-ip-filter']" "0" '${JSON.stringify(filters)}'`,
    `ruby_uniq "$CONFIG_FILE" "['dns']['fake-ip-filter']"`,
    "",
  ].join("\n"));
}

main();
